/* Copies the fonts the UI uses out of node_modules into shared/fonts and
   writes shared/fonts/fonts.css, so pages never call Google Fonts. */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const out = path.join(root, "shared", "fonts");
fs.mkdirSync(out, { recursive: true });
const mod = (...parts) => path.join(root, "node_modules", ...parts);

const faces = [];
const copy = (src, name) => {
  if (!fs.existsSync(src)) throw new Error(`missing ${src} — run npm install`);
  fs.copyFileSync(src, path.join(out, name));
};

for (const [pkg, family, weights] of [["inter", "Inter", [400, 500, 600, 700]], ["manrope", "Manrope", [400, 600, 700]]]) {
  for (const weight of weights) {
    const file = `${pkg}-latin-${weight}-normal.woff2`;
    copy(mod("@fontsource", pkg, "files", file), file);
    faces.push(`@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;src:url("${file}") format("woff2");}`);
  }
}

copy(mod("material-symbols", "material-symbols-outlined.woff2"), "material-symbols-outlined.woff2");
faces.push(`@font-face{font-family:"Material Symbols Outlined";font-style:normal;font-weight:100 700;font-display:block;src:url("material-symbols-outlined.woff2") format("woff2");}`);
faces.push(`.material-symbols-outlined{font-family:"Material Symbols Outlined";font-weight:normal;font-style:normal;font-size:24px;line-height:1;letter-spacing:normal;text-transform:none;display:inline-block;white-space:nowrap;word-wrap:normal;direction:ltr;-webkit-font-feature-settings:"liga";font-feature-settings:"liga";-webkit-font-smoothing:antialiased;}`);

fs.writeFileSync(path.join(out, "fonts.css"), `/* Generated by scripts/build-fonts.js — do not edit. */\n${faces.join("\n")}\n`);
console.log(`fonts: ${faces.length - 1} faces written to shared/fonts`);
